"""Phase 4E: proposer x feedback, with an equal-budget stochastic control.

The Phase-4A table repaired only the TCN. That leaves the architecture question unanswered:
does the learned proposer contribute after output-level geometric feedback, or does the same
repair operator make a cheap heuristic just as safe? This experiment runs the complete matrix

    heuristic, QP, TCN x 0, 1, 2 verification-guided repairs

and, at the same maximum adapted-generation budgets, unchanged-proposal controls:

    heuristic, QP, TCN x best verified of 2 or 3 independent generator samples.

Repair keeps the generator seed fixed and changes only the proposal. Resampling keeps the
proposal byte-identical and changes only the generator seed. Both stop on the first candidate
that is collision-free and meets the target; otherwise resampling selects its best candidate by
a predeclared measured-geometry rule.

`ardy_calls` and `necessary_adapted_generations` are now the same architecture/computation axis:
one candidate-producing generation per attempt, independent of cache state. The redundant path
reference generated by the legacy implementation has been removed; `legacy_ardy_calls` records
its old two-per-attempt accounting for comparison with historical tables.

GPU-heavy generation is intentionally not part of the test suite. Typical invocation:

    python -m scene2motion.verify.experiment_architecture --seeds 100
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import time
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

from ..demo.cache import CACHE_VERSION, ClipCache
from ..demo.scene_builder import BeamParams, build
from ..demo.schedules import RESP_PATH, SPEED, TCN_DIR, all_schedules, response
from ..demo.strategy_planner import evaluate
from ..optim.response import DIP_MAX
from ..optim.scheduler import MARGIN_M
from ..runner import NOISE_STREAM_VERSION
from .experiment_repair import STAND_TOP, _aggregate, _row
from .loop import RESAMPLE_SEED_STRIDE, run, run_resample
from .trace import schedule_hash

OUT = Path("outputs/phase4e_architecture")
CACHE = Path("scene2motion/demo_outputs/clips")
PROPOSERS = ("heuristic", "qp", "tcn")
SCHEDULE_KEYS = {"heuristic": "heuristic", "qp": "optimizer", "tcn": "optimized"}


@dataclass(frozen=True)
class MethodSpec:
    name: str
    proposer: str
    feedback: str
    max_adapted_generations: int

    @property
    def schedule_key(self) -> str:
        return SCHEDULE_KEYS[self.proposer]

    @property
    def max_repairs(self) -> int:
        return self.max_adapted_generations - 1 if self.feedback != "resample_select" else 0


def build_method_specs(proposers=PROPOSERS, repair_budgets=(0, 1, 2),
                       resample_budgets=(2, 3)) -> tuple[MethodSpec, ...]:
    """Build a deterministic matrix while preserving the original Phase-4 method names."""
    bad = [p for p in proposers if p not in PROPOSERS]
    if bad:
        raise ValueError(f"unknown proposer(s): {bad}")
    repair_budgets = tuple(dict.fromkeys(int(x) for x in repair_budgets))
    resample_budgets = tuple(dict.fromkeys(int(x) for x in resample_budgets))
    if any(x < 0 for x in repair_budgets):
        raise ValueError("repair budgets must be non-negative")
    if any(x < 2 for x in resample_budgets):
        raise ValueError("resampling budgets must be at least two")

    specs = []
    for proposer in proposers:
        for n_repairs in repair_budgets:
            name = proposer if n_repairs == 0 else f"{proposer}+{n_repairs}"
            specs.append(MethodSpec(name, proposer,
                                    "none" if n_repairs == 0 else "repair",
                                    n_repairs + 1))
        for n_samples in resample_budgets:
            specs.append(MethodSpec(f"{proposer}-resample{n_samples}", proposer,
                                    "resample_select", n_samples))
    names = [s.name for s in specs]
    if len(names) != len(set(names)):
        raise ValueError(f"duplicate method names: {names}")
    return tuple(specs)


def _sha256(path: Path) -> str | None:
    if not path.exists():
        return None
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _git_state(repo: Path) -> dict:
    """Commit plus dirty-state evidence; never guess when the workspace is unavailable."""
    try:
        commit = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=repo, text=True,
            stderr=subprocess.DEVNULL).strip()
        status = subprocess.check_output(
            ["git", "status", "--short"], cwd=repo, text=True,
            stderr=subprocess.DEVNULL).splitlines()
        diff = subprocess.check_output(
            ["git", "diff", "--binary", "HEAD"], cwd=repo,
            stderr=subprocess.DEVNULL)
        return {"commit": commit, "dirty": bool(status), "status": status,
                "tracked_diff_sha256": hashlib.sha256(diff).hexdigest()}
    except (OSError, subprocess.CalledProcessError):
        return {"commit": None, "dirty": None, "status": [],
                "tracked_diff_sha256": None}


def frozen_provenance(tcn_dir: Path, response_path: Path = RESP_PATH,
                      require_tcn: bool = True, repo: Path | None = None) -> dict:
    """Hash every learned artifact whose identity can change the matrix."""
    tcn_dir = tcn_dir.resolve()
    pt, meta_path = tcn_dir / "tcn.pt", tcn_dir / "tcn.json"
    if require_tcn and (not pt.exists() or not meta_path.exists()):
        raise FileNotFoundError(f"incomplete TCN checkpoint at {tcn_dir}")
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    if require_tcn and abs(float(meta.get("margin_m", -1)) - MARGIN_M) > 1e-9:
        raise ValueError(f"checkpoint margin {meta.get('margin_m')} != {MARGIN_M}")
    response_path = response_path.resolve()
    if not response_path.exists():
        raise FileNotFoundError(f"duck response not found at {response_path}")
    repo = (repo or Path(__file__).resolve().parents[2]).resolve()
    package = Path(__file__).resolve().parents[1]
    source_paths = [Path(__file__).resolve(), Path(run.__code__.co_filename).resolve(),
                    Path(_row.__code__.co_filename).resolve(), package / "runner.py",
                    package / "demo" / "cache.py"]
    return {
        "code": _git_state(repo),
        # Direct hashes make a dirty or not-yet-added experiment reproducible too; git diff
        # alone cannot fingerprint untracked source files.
        "source_sha256": {str(p.relative_to(repo) if p.is_relative_to(repo) else p): _sha256(p)
                          for p in dict.fromkeys(source_paths)},
        "tcn": {"directory": str(tcn_dir), "checkpoint": str(pt),
                "checkpoint_sha256": _sha256(pt), "metadata": str(meta_path),
                "metadata_sha256": _sha256(meta_path),
                "dataset": meta.get("dataset"), "dataset_hash": meta.get("dataset_hash"),
                "margin_m": meta.get("margin_m"), "training_seed": meta.get("seed")},
        "duck_response": {"path": str(response_path), "sha256": _sha256(response_path)},
        "generation_identity": {"noise_stream_version": NOISE_STREAM_VERSION,
                                "clip_cache_version": CACHE_VERSION},
    }


def _run_method(spec: MethodSpec, scene, plan, q0, resp, cache, *, preference, seed,
                seed_stride, provenance, allow_generate=True):
    if spec.feedback == "resample_select":
        return run_resample(scene, plan, q0, cache, preference=preference, seed=seed,
                            max_samples=spec.max_adapted_generations,
                            seed_stride=seed_stride, provenance=provenance,
                            allow_generate=allow_generate)
    return run(scene, plan, q0, resp, cache, preference=preference, seed=seed,
               max_repairs=spec.max_repairs, provenance=provenance,
               allow_generate=allow_generate)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n-beams", type=int, nargs="+", default=[3, 4, 5, 6])
    ap.add_argument("--heights", type=float, nargs="+", default=[0.95, 1.05, 1.20])
    ap.add_argument("--gaps", type=float, nargs="+", default=[1.5, 2.5, 3.5])
    ap.add_argument("--width", type=float, default=2.25)
    ap.add_argument("--seeds", type=int, nargs="+", default=[100])
    ap.add_argument("--preference", default="shortest")
    ap.add_argument("--proposers", nargs="+", choices=PROPOSERS, default=list(PROPOSERS))
    ap.add_argument("--repair-budgets", type=int, nargs="+", default=[0, 1, 2],
                    help="number of geometry-driven corrections; 0 preserves one-shot names")
    ap.add_argument("--resample-budgets", type=int, nargs="*", default=[2, 3],
                    help="unchanged-proposal sample counts; pass no values to omit controls")
    ap.add_argument("--resample-seed-stride", type=int, default=RESAMPLE_SEED_STRIDE)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--cache", type=Path, default=CACHE)
    ap.add_argument("--tcn-dir", type=Path, default=TCN_DIR)
    ap.add_argument("--no-generate", action="store_true",
                    help="inventory cached cells only; record every miss as unverified")
    a = ap.parse_args()

    specs = build_method_specs(a.proposers, a.repair_budgets, a.resample_budgets)
    frozen = frozen_provenance(a.tcn_dir, require_tcn="tcn" in a.proposers)
    resp = response()
    if resp is None:
        raise SystemExit("no fitted duck response")
    cache = ClipCache(a.cache)
    a.out.mkdir(parents=True, exist_ok=True)

    rows, skipped, t0 = [], [], time.time()
    combos = [(n, h, g) for h in a.heights for n in a.n_beams for g in a.gaps]
    for n, h, g in combos:
        bp = BeamParams(beam_height=h, beam_width=a.width, n_beams=n, gap=g).clamped()
        sc = build(bp)
        st = evaluate(sc, a.preference)
        if not st.feasible:
            skipped.append({"beam": bp.__dict__, "why": "route infeasible"})
            continue
        sched = all_schedules(sc, st.plan, speed=SPEED, tcn_dir=a.tcn_dir)
        if "tcn" in a.proposers and sched.get("tcn_dataset_hash") != frozen["tcn"]["dataset_hash"]:
            raise RuntimeError("loaded TCN provenance does not match the frozen checkpoint")
        s_m = np.asarray(sched["s_m"], float)
        needed = max(0.0, STAND_TOP - h)
        prov_base = {"beam": bp.__dict__, "tcn_dataset_hash": sched.get("tcn_dataset_hash"),
                     "tcn_margin_m": sched.get("tcn_margin_m"),
                     "tcn_checkpoint_sha256": frozen["tcn"]["checkpoint_sha256"],
                     "duck_response_sha256": frozen["duck_response"]["sha256"],
                     "code_commit": frozen["code"]["commit"],
                     "code_tracked_diff_sha256": frozen["code"]["tracked_diff_sha256"],
                     "route_len_m": sched["route_len_m"], "needed_dip_m": needed,
                     "tcn_dir": sched.get("tcn_dir")}

        for spec in specs:
            dip = sched["schedules"].get(spec.schedule_key)
            if dip is None:
                why = f"no {spec.proposer} schedule"
                if spec.proposer == "tcn":
                    raise RuntimeError(why)
                skipped.append({"beam": bp.__dict__, "method": spec.name, "why": why})
                continue
            q0 = np.clip(np.asarray(dip, float) / DIP_MAX, 0.0, 1.0)
            for seed in a.seeds:
                method_prov = {**prov_base, "method": spec.name,
                               "proposer": spec.proposer, "feedback": spec.feedback,
                               "max_adapted_generations": spec.max_adapted_generations,
                               "schedule_hash": schedule_hash(q0)}
                result = _run_method(spec, sc, st.plan, q0, resp, cache,
                                     preference=a.preference, seed=seed,
                                     seed_stride=a.resample_seed_stride,
                                     provenance=method_prov,
                                     allow_generate=not a.no_generate)
                row = _row(sc, bp, spec.name, result, needed, s_m, seed)
                row.update({"proposer": spec.proposer, "feedback": spec.feedback,
                            "max_adapted_generation_budget": spec.max_adapted_generations})
                rows.append(row)
                print(f"n={n} h={h:.2f} g={g:.1f} {spec.name:22s} seed={seed}: "
                      f"{row['outcome']:16s} over={row.get('min_overhead_m', float('nan')):+.4f} "
                      f"free={str(row.get('collision_free')):5s} "
                      f"target={str(row.get('meets_target')):5s} "
                      f"gen={row['necessary_adapted_generations']}/"
                      f"{spec.max_adapted_generations}", flush=True)

    by = defaultdict(list)
    for row in rows:
        if "collision_free" in row and row["outcome"] != "unverified":
            by[row["method"]].append(row)
    summary = {spec.name: _aggregate(by[spec.name]) for spec in specs if by[spec.name]}
    by_count = {spec.name: {
        str(n): _aggregate([r for r in by[spec.name] if r["n_beams"] == n])
        for n in a.n_beams if [r for r in by[spec.name] if r["n_beams"] == n]}
        for spec in specs if by[spec.name]}

    repairs = [p for row in rows for p in row.get("repairs", [])]
    repair_stats = {"n_repair_steps": len(repairs)}
    if repairs:
        repair_stats.update({
            "mean_magnitude_m": round(float(np.mean(
                [p["repair_magnitude_m"] for p in repairs])), 4),
            "max_magnitude_m": round(float(np.max(
                [p["repair_magnitude_m"] for p in repairs])), 4),
            "mean_onset_shift_m": round(float(np.mean(
                [p["onset_shift_m"] for p in repairs])), 4),
            "mean_duration_change_m": round(float(np.mean(
                [p["duration_change_m"] for p in repairs])), 4),
            "slope_floor_bound_steps": int(sum(
                1 for p in repairs if p["slope_floor_bound"] > 0))})

    unverified = [{"scene_id": row["scene_id"], "method": row["method"],
                   "seed": row["seed"], "reason": row["reason"],
                   "n_cached_attempts": row["n_attempts"]}
                  for row in rows if row["outcome"] == "unverified"]
    payload = {
        "generated_at": time.time(), "elapsed_s": round(time.time() - t0, 1),
        "experiment": "phase4e_proposer_feedback_architecture",
        "target_m": MARGIN_M, "preference": a.preference, "width_m": a.width,
        "n_beams": a.n_beams, "heights": a.heights, "gaps": a.gaps,
        "seeds": a.seeds, "resample_seed_stride": a.resample_seed_stride,
        "allow_generate": not a.no_generate,
        "tcn_dir": str(a.tcn_dir), "stand_top_m": STAND_TOP,
        "method_specs": [{**asdict(spec), "schedule_key": spec.schedule_key,
                          "max_repairs": spec.max_repairs} for spec in specs],
        "cost_accounting": {
            "primary": "necessary_adapted_generations",
            "necessary_adapted_generations":
                "one candidate-producing ARDY generation per attempted clip",
            "ardy_calls": "one candidate-producing ARDY invocation per attempt",
            "legacy_ardy_calls":
                "historical v1 implementation: candidate plus unused path reference",
            "executed_fields": "cache-dependent diagnostics, not method complexity",
            "budget_semantics": "maximum adapted generations; methods stop on target acceptance",
        },
        "frozen_provenance": frozen,
        "summary": summary, "by_beam_count": by_count,
        "summary_complete": len(unverified) == 0,
        "repair_stats": repair_stats, "n_skipped": len(skipped), "skipped": skipped,
        "n_unverified": len(unverified), "unverified": unverified,
        "rows": rows,
    }
    (a.out / "experiment.json").write_text(json.dumps(payload, indent=2))

    print(f"\n{len(rows)} runs, {len(skipped)} skipped, {time.time()-t0:.0f}s\n")
    print(f"{'method':23s} {'n':>4s} {'coll-free':>10s} {'meets .18':>10s} "
          f"{'calls':>8s} {'old-v1':>7s} {'peak dip':>9s} {'int duck':>9s}")
    for spec in specs:
        if spec.name not in summary:
            continue
        s = summary[spec.name]
        print(f"{spec.name:23s} {s['n']:4d} {s['collision_free_rate']:10.3f} "
              f"{s['margin_satisfaction_rate']:10.3f} "
              f"{s['mean_necessary_adapted_generations']:8.2f} "
              f"{s['mean_legacy_ardy_calls']:7.2f} {s['mean_peak_dip_m']*100:8.1f}cm "
              f"{s['mean_duck_integral_m2']:9.3f}")
    print(f"\nrepair steps: {repair_stats}")
    print(f"-> {a.out / 'experiment.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
